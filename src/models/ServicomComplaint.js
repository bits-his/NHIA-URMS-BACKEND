const { DataTypes } = require("sequelize");
const sequelize = require("../config/database");

/**
 * SERVICOM Complaints Management — header.
 * Primary key is system-generated complaint_number (ENF/...). No auto-increment id.
 */
const ServicomComplaint = sequelize.define(
  "ServicomComplaint",
  {
    complaint_number: {
      type: DataTypes.STRING(60),
      allowNull: false,
      primaryKey: true,
    },
    zonal_code: {
      type: DataTypes.STRING(20),
      allowNull: false,
      references: { model: "zonal_offices", key: "zonal_code" },
      onUpdate: "CASCADE",
      onDelete: "RESTRICT",
    },
    state_code: {
      type: DataTypes.STRING(20),
      allowNull: false,
      references: { model: "state_offices", key: "code" },
      onUpdate: "CASCADE",
      onDelete: "RESTRICT",
    },
    unit_code: {
      type: DataTypes.STRING(20),
      allowNull: true,
      references: { model: "units", key: "unit_code" },
      onUpdate: "CASCADE",
      onDelete: "SET NULL",
    },
    reporting_month: { type: DataTypes.TINYINT.UNSIGNED, allowNull: true },
    reporting_year: { type: DataTypes.SMALLINT.UNSIGNED, allowNull: true },
    entry_date: { type: DataTypes.DATEONLY, allowNull: true },
    complaint_date: { type: DataTypes.DATEONLY, allowNull: false },
    complaint_type: { type: DataTypes.STRING(80), allowNull: true },
    complaint_against: { type: DataTypes.STRING(80), allowNull: true },
    complaint_category: { type: DataTypes.STRING(80), allowNull: true },
    category_code: { type: DataTypes.STRING(30), allowNull: true },
    complaint_domain: { type: DataTypes.STRING(80), allowNull: true },
    domain_code: { type: DataTypes.STRING(30), allowNull: true },
    offence_reference: { type: DataTypes.STRING(30), allowNull: true },
    priority_rating: { type: DataTypes.STRING(20), allowNull: true },
    date_received: { type: DataTypes.DATEONLY, allowNull: true },
    transmission_route: { type: DataTypes.STRING(80), allowNull: true },
    complainant_category: { type: DataTypes.STRING(80), allowNull: true },
    complainant_id: { type: DataTypes.STRING(100), allowNull: true },
    complainant_name: { type: DataTypes.STRING(200), allowNull: true },
    complainant_organization: { type: DataTypes.STRING(200), allowNull: true },
    complainant_phone: { type: DataTypes.STRING(80), allowNull: true },
    complainant_nhis_id: { type: DataTypes.STRING(100), allowNull: true },
    complainant_hmo_code: {
      type: DataTypes.STRING(40),
      allowNull: true,
      references: { model: "hmo_providers", key: "hmo_code" },
      onUpdate: "CASCADE",
      onDelete: "SET NULL",
    },
    complainant_hcf_code: { type: DataTypes.STRING(100), allowNull: true },
    complainant_hcf_name: { type: DataTypes.STRING(200), allowNull: true },
    respondent_category: { type: DataTypes.STRING(80), allowNull: true },
    respondent_id: { type: DataTypes.STRING(100), allowNull: true },
    respondent_name: { type: DataTypes.STRING(200), allowNull: true },
    respondent_organization: { type: DataTypes.STRING(200), allowNull: true },
    respondent_phone: { type: DataTypes.STRING(80), allowNull: true },
    respondent_nhis_id: { type: DataTypes.STRING(100), allowNull: true },
    respondent_hmo_code: {
      type: DataTypes.STRING(40),
      allowNull: true,
      references: { model: "hmo_providers", key: "hmo_code" },
      onUpdate: "CASCADE",
      onDelete: "SET NULL",
    },
    respondent_hcf_code: { type: DataTypes.STRING(100), allowNull: true },
    respondent_hcf_name: { type: DataTypes.STRING(200), allowNull: true },
    officer_assigned: { type: DataTypes.STRING(150), allowNull: true },
    investigation_start_date: { type: DataTypes.DATEONLY, allowNull: true },
    status: {
      type: DataTypes.STRING(50),
      allowNull: false,
      defaultValue: "New/Acknowledged",
    },
    actions_taken: { type: DataTypes.JSON, allowNull: true, defaultValue: [] },
    actions_details: { type: DataTypes.TEXT, allowNull: true },
    escalated: { type: DataTypes.BOOLEAN, allowNull: false, defaultValue: false },
    escalation_level: { type: DataTypes.STRING(80), allowNull: true },
    escalation_date: { type: DataTypes.DATEONLY, allowNull: true },
    escalated_to: { type: DataTypes.STRING(80), allowNull: true },
    resolution_days: { type: DataTypes.INTEGER.UNSIGNED, allowNull: true },
    resolution_within_sla: { type: DataTypes.BOOLEAN, allowNull: true },
    date_closed: { type: DataTypes.DATEONLY, allowNull: true },
    outcome: { type: DataTypes.STRING(80), allowNull: true },
    remarks: { type: DataTypes.TEXT, allowNull: true },
    description: { type: DataTypes.TEXT, allowNull: true },
    created_by_user_id: {
      type: DataTypes.INTEGER.UNSIGNED,
      allowNull: true,
      references: { model: "users", key: "id" },
      onDelete: "SET NULL",
      onUpdate: "CASCADE",
    },
  },
  {
    tableName: "servicom_complaints",
    modelName: "ServicomComplaint",
    indexes: [
      { fields: ["state_code", "date_received"] },
      { fields: ["zonal_code", "date_received"] },
      { fields: ["status"] },
      { fields: ["priority_rating"] },
    ],
  },
);

module.exports = ServicomComplaint;
